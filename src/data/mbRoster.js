function createRosterEntry(row) {
  const [dex, id, name, primaryType, secondaryType, formImageId] = row.split('|')
  const nationalDex = Number(dex)

  return Object.freeze({
    id,
    nationalDex,
    name,
    types: Object.freeze([primaryType, secondaryType].filter(Boolean)),
    image: getPokemonImage(nationalDex, formImageId || nationalDex),
  })
}

export const MB_ROSTER = Object.freeze(rosterRows.map(createRosterEntry))
export const MB_ROSTER_COUNT = MB_ROSTER.length
